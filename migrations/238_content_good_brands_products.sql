-- Migración 238: Tipos de Bien + Productos + Marcas
-- ═══════════════════════════════════════════════════════════════
--
-- Estructura jerárquica para daños de contenido:
--   content_good_types   (Tipos de Bien — raíz, ej: Electrodomésticos)
--     └── content_good_products (Productos — hoja, ej: Refrigerador)
--   content_good_brands  (Marcas — catálogo global, ej: Samsung)
--
-- Modelo:
--   - Marca es GLOBAL (no se duplica). Samsung existe 1 vez.
--   - Producto es genérico (sin marca). "Lavadora" existe 1 vez.
--   - En inspection_damages, el inspector combina:
--       product_id (FK a content_good_products)
--       brand_id   (FK a content_good_brands)
--     Así "Lavadora Samsung" y "Lavadora LG" son el mismo producto
--     con distinta marca, sin duplicar el catálogo.
--
-- Cambios sobre content_good_types existentes (migración 159):
--   - Renombramientos (UPDATE, no toca IDs ni datos):
--       Maquinaria           → Maquinaria y Herramientas
--       Enseres Generales    → Enseres de Cocina
--       Móviles              → Computación y Móviles
--       Electrónica          → (mismo nombre, descripción afinada)
--       Joyas / Bisutería    → (mismo nombre, descripción afinada)
--   - 4 tipos nuevos (INSERT):
--       Alimentos / Víveres
--       Jardinería / Exterior
--       Seguridad / Smart Home
--       Óptica / Astronomía
--
-- Cambios sobre inspection_damages:
--   - ADD COLUMN product_id (FK a content_good_products, nullable)
--   - ADD COLUMN brand_id   (FK a content_good_brands, nullable)
--   Las columnas product/brand_model (TEXT libres) se conservan.
-- ═══════════════════════════════════════════════════════════════

-- ── 1. content_good_brands (Marcas — catálogo global) ──
CREATE TABLE IF NOT EXISTS content_good_brands (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL,
  country TEXT,
  is_active BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

ALTER TABLE content_good_brands ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "content_good_brands_select" ON content_good_brands;
DROP POLICY IF EXISTS "content_good_brands_all" ON content_good_brands;
CREATE POLICY "content_good_brands_select" ON content_good_brands FOR SELECT USING (true);
CREATE POLICY "content_good_brands_all" ON content_good_brands FOR ALL USING (true) WITH CHECK (true);

-- ── 2. content_good_products (Productos — hoja de tipos de bien) ──
CREATE TABLE IF NOT EXISTS content_good_products (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  content_good_type_id UUID NOT NULL REFERENCES content_good_types(id) ON DELETE RESTRICT,
  name TEXT NOT NULL,
  description TEXT,
  sort_order INTEGER DEFAULT 0,
  is_active BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

ALTER TABLE content_good_products ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "content_good_products_select" ON content_good_products;
DROP POLICY IF EXISTS "content_good_products_all" ON content_good_products;
CREATE POLICY "content_good_products_select" ON content_good_products FOR SELECT USING (true);
CREATE POLICY "content_good_products_all" ON content_good_products FOR ALL USING (true) WITH CHECK (true);

-- Índice para filtrar productos por tipo
CREATE INDEX IF NOT EXISTS idx_content_good_products_type_id ON content_good_products(content_good_type_id);
CREATE INDEX IF NOT EXISTS idx_content_good_products_active ON content_good_products(is_active);

-- ── 3. inspection_damages: agregar product_id y brand_id ──
ALTER TABLE inspection_damages
  ADD COLUMN IF NOT EXISTS product_id UUID REFERENCES content_good_products(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS brand_id UUID REFERENCES content_good_brands(id) ON DELETE SET NULL;

COMMENT ON COLUMN inspection_damages.product_id IS 'Producto del catálogo (FK a content_good_products). Nullable para compatibilidad con datos existentes.';
COMMENT ON COLUMN inspection_damages.brand_id IS 'Marca del catálogo (FK a content_good_brands). Nullable para compatibilidad con datos existentes.';

